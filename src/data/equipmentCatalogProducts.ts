/**
 * Returns all allowed equipment products (Category 1, 2, and 3).
 * Explicitly guards against any dental items.
 */
export function getAllPermittedEquipmentProducts(): EquipmentProductReference[] {
  return RAW_EQUIPMENT_CATALOG.filter(
    (p) =>
      p.category !== 'تجهیزات دندانپزشکی' &&
      !p.category.includes('دندان') &&
      !p.subcategory.includes('دندان')
  );
}

/**
 * Search equipment products by Persian or English name, category, or subcategory.
 */
export function searchPermittedEquipmentProducts(
  query: string,
  catalog: EquipmentProductReference[] = getAllPermittedEquipmentProducts()
): EquipmentProductReference[] {
  if (!query || !query.trim()) {
    return catalog;
  }
  const cleanQ = query.trim().toLowerCase();
  return catalog.filter((p) => {
    return (
      p.name.toLowerCase().includes(cleanQ) ||
      p.enName.toLowerCase().includes(cleanQ) ||
      p.subcategory.toLowerCase().includes(cleanQ) ||
      p.type.toLowerCase().includes(cleanQ) ||
      (p.umdns && p.umdns.includes(cleanQ))
    );
  });
}

/**
 * Resolves the taxonomy node and inherited requirement fields for a product.
 */
export function resolveTaxonomyForProduct(
  product: EquipmentProductReference,
  classificationsList: AssetClassification[] = INITIAL_STRUCTURES_DATA
): {
  categoryId?: string;
  subcategoryId?: string;
  typeId?: string;
  categoryName: string;
  subcategoryName: string;
  typeName: string;
  inheritedFields: { levelLabel: string; field: AssetRequirementField }[];
} {
  // Find matching classification nodes
  // 1. Find category
  const catNode = classificationsList.find(
    (c) => !c.parentId && c.name.trim() === product.category.trim()
  );

  // 2. Find subcategory
  const subNode = classificationsList.find(
    (c) =>
      (catNode ? c.parentId === catNode.id : true) &&
      c.name.trim().toLowerCase() === product.subcategory.trim().toLowerCase()
  );

  // 3. Find type
  const typeNode = classificationsList.find(
    (c) =>
      (subNode ? c.parentId === subNode.id : true) &&
      (c.name.trim().toLowerCase() === product.type.trim().toLowerCase() ||
        c.name.trim().toLowerCase() === product.name.trim().toLowerCase())
  );

  const targetNodeId = typeNode?.id || subNode?.id || catNode?.id || '';
  const inheritedFields = targetNodeId
    ? getInheritedFieldsForNode(targetNodeId, classificationsList)
    : [];

  return {
    categoryId: catNode?.id,
    subcategoryId: subNode?.id,
    typeId: typeNode?.id,
    categoryName: product.category,
    subcategoryName: product.subcategory,
    typeName: product.type,
    inheritedFields,
  };
}
